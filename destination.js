// =====================================================
// GET DESTINATION FROM URL
// =====================================================

// Example:
// destination.html?place=manali

const params =
    new URLSearchParams(window.location.search);

const place =
    params.get("place");


// =====================================================
// GET DESTINATION
// =====================================================

const destination =
    destinations[place];


// =====================================================
// IF DESTINATION DOES NOT EXIST
// =====================================================

if (!destination) {

    document.body.innerHTML = `

        <div class="error-page">

            <h1>Destination Not Found</h1>

            <p>
                Sorry, we couldn't find this destination.
            </p>

            <a href="index.html">
                Go Back Home
            </a>

        </div>

    `;

}


// =====================================================
// DISPLAY DESTINATION
// =====================================================

else {

    // Main Image

    document.getElementById(
        "destination-image"
    ).src = destination.image;


    document.getElementById(
        "destination-image"
    ).alt = destination.name;


    // State

    document.getElementById(
        "destination-state"
    ).textContent = destination.state;


    // Name

    document.getElementById(
        "destination-name"
    ).textContent = destination.name;


    // Description

    document.getElementById(
        "destination-description"
    ).textContent = destination.description;


    // About

    document.getElementById(
        "about-title"
    ).textContent =
        `Discover ${destination.name}`;


    document.getElementById(
        "about-text"
    ).textContent = destination.about;


    // =================================================
    // CREATE IMAGE CARD
    // =================================================

    function createImageCard(item) {

        const card =
            document.createElement("div");

        card.classList.add("info-card");


        const image =
            document.createElement("img");

        image.src = item.image;

        image.alt = item.name;

        image.loading = "lazy";


        const content =
            document.createElement("div");

        content.classList.add("card-content");


        const title =
            document.createElement("h3");

        title.textContent = item.name;


        content.appendChild(title);

        card.appendChild(image);

        card.appendChild(content);


        return card;

    }


    // =================================================
    // PLACES
    // =================================================

    const placesContainer =
        document.getElementById(
            "places-container"
        );

    destination.places.forEach(function (place) {

        placesContainer.appendChild(
            createImageCard(place)
        );

    });


    // =================================================
    // HOTELS
    // =================================================

    const hotelsContainer =
        document.getElementById(
            "hotels-container"
        );

    destination.hotels.forEach(function (hotel) {

        hotelsContainer.appendChild(
            createImageCard(hotel)
        );

    });


    // =================================================
    // FOOD
    // =================================================

    const foodContainer =
        document.getElementById(
            "food-container"
        );

    destination.food.forEach(function (food) {

        foodContainer.appendChild(
            createImageCard(food)
        );

    });


    // =================================================
    // TRAVEL TIPS
    // =================================================

    const tipsContainer =
        document.getElementById(
            "tips-container"
        );


    destination.tips.forEach(function (tip) {

        const card =
            document.createElement("div");

        card.classList.add("tip-card");


        card.textContent = tip;


        tipsContainer.appendChild(card);

    });

}